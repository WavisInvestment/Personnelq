'use client';

import { useEffect, useRef, useState } from 'react';
import { Alert } from '@/components/ui/alert';
import { Button } from '@/components/ui/button';
import { INSIGHT_SECTIONS, readApiProblem, formatDate, type Insights } from '@/lib/assessments';
import { generateInsights } from '@/lib/billing';

export function InsightsPanel({
  resultId,
  initial,
  generatedAt,
  available,
  snapshot = false,
  onGenerated,
}: {
  resultId: string;
  initial: Insights | null;
  generatedAt: string | null;
  available: boolean;
  /** The free snapshot's short analysis: written as soon as the page opens, three sections. */
  snapshot?: boolean;
  onGenerated: (insights: Insights, generatedAt: string | null) => void;
}) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');

  const generate = async () => {
    setBusy(true);
    setError('');
    try {
      const res = await generateInsights(resultId);
      onGenerated(res.insights, res.generated_at);
    } catch (err) {
      setError(readApiProblem(err).message);
    } finally {
      setBusy(false);
    }
  };

  // The free analysis is part of the result, so it is written on first view instead of waiting for a click.
  const auto = useRef(false);
  useEffect(() => {
    if (snapshot && available && !initial && !auto.current) {
      auto.current = true;
      void generate();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [snapshot, available, initial]);

  if (!initial && snapshot) {
    return (
      <section aria-labelledby="insights-heading" className="border-t border-line py-6 sm:py-8">
        <h2 id="insights-heading" className="font-display text-2xl font-bold tracking-[-0.03em]">
          Your first read
        </h2>
        {error && <Alert tone="error" className="mt-5">{error}</Alert>}
        {!available ? (
          <Alert tone="info" className="mt-5">The written analysis isn’t available right now. Please check back soon.</Alert>
        ) : error ? (
          <Button className="mt-5" variant="secondary" onClick={generate} loading={busy}>
            Try again
          </Button>
        ) : (
          <p className="mt-3 animate-pulse text-[15px] text-ink-muted" role="status">Writing your analysis. This can take up to half a minute…</p>
        )}
      </section>
    );
  }

  if (!initial) {
    return (
      <section aria-labelledby="insights-heading" className="py-6 sm:py-8 border-t border-line">
        <h2 id="insights-heading" className="font-display text-2xl font-medium">
          Your written insights
        </h2>
        <p className="mt-2 max-w-2xl text-[15px] leading-relaxed text-ink-soft">
          A personal reading of your five scores: how you communicate, lead, work and relate to others, plus your strengths,
          blind spots and next steps. Only your five scores are used to write it, never your name or email.
        </p>
        {error && <Alert tone="error" className="mt-5">{error}</Alert>}
        {available ? (
          <Button className="mt-6" onClick={generate} loading={busy}>
            {busy ? 'Writing your insights…' : 'Write my insights'}
          </Button>
        ) : (
          <Alert tone="info" className="mt-5">Written insights aren’t available right now. Please check back soon.</Alert>
        )}
        {busy && <p className="mt-3 text-sm text-ink-muted">This can take up to half a minute.</p>}
      </section>
    );
  }

  return (
    <section aria-labelledby="insights-heading">
      <div className="flex flex-wrap items-baseline justify-between gap-2">
        <h2 id="insights-heading" className="font-display text-3xl font-medium">
          {snapshot ? 'Your written analysis' : 'Your written insights'}
        </h2>
        {generatedAt && <p className="text-sm text-ink-muted">Written {formatDate(generatedAt)}</p>}
      </div>
      <p className="mt-1 text-sm text-ink-muted">Generated by AI from your scores. It’s a starting point for reflection, not a diagnosis.</p>

      <div className="mt-6 grid gap-5 md:grid-cols-2">
        {INSIGHT_SECTIONS.filter(([key]) => initial[key]).map(([key, title]) => {
          const section = initial[key]!;
          return (
            <article key={key} className="p-6 rounded-xl bg-paper-soft">
              <h3 className="font-display text-xl font-medium">{snapshot && key === 'personality' ? 'Your first read' : snapshot && key === 'strengths' ? 'What you do well' : title}</h3>
              <p className="mt-2 text-[15px] leading-relaxed text-ink-soft">{section.summary}</p>
              <ul className="mt-4 space-y-2 text-[15px] leading-relaxed text-ink-soft">
                {section.points.map((point, i) => (
                  <li key={i} className="flex gap-3">
                    <span aria-hidden="true" className="mt-2.5 h-1.5 w-1.5 shrink-0 rounded-full bg-brand-500" />
                    <span>{point}</span>
                  </li>
                ))}
              </ul>
            </article>
          );
        })}
      </div>
    </section>
  );
}
